export function checkWSContrast() {
  return Object.entries(wsThemes).flatMap(([theme, colors]) =>
    wsPairs.map(([foreground, background, minimum]) => ({
      theme,
      foreground,
      background,
      minimum,
      ratio: contrastRatio(colors[foreground], colors[background]),
    })),
  );
}
